// The language the toolbar speaks: Chinese on a Chinese system, English on any other, unless the
//   `language` setting forces one. Every on-screen string and every prompt sent to Claude lives here.
import type { EngineInterface } from 'claude-code'

export type Lang = 'zh' | 'en'

// A locale or language tag: zh* is Chinese; any other real tag is English; C, POSIX or nothing decides nothing.
export function langOf(tag: string | undefined): Lang | undefined {
  const t = (tag ?? '').trim()
  if (!t) return undefined
  if (/^zh/i.test(t)) return 'zh'
  const base = t.split(/[.@]/)[0] ?? ''
  return base === 'C' || base === 'POSIX' || base === '' ? undefined : 'en'
}

// The setting when it names a language; else the locale variables; else the system's own first
//   language. Any failure reads as English. Never throws.
export async function detectLang($: Pick<EngineInterface, 'env' | 'process'>, setting: unknown): Promise<Lang> {
  if (setting === 'zh' || setting === 'en') return setting
  try {
    const env = async (read: () => Promise<string | undefined>) => langOf(await read().catch(() => undefined))
    const fromEnv = (await env(() => $.env.get('LC_ALL'))) ?? (await env(() => $.env.get('LC_MESSAGES'))) ?? (await env(() => $.env.get('LANG')))
    if (fromEnv) return fromEnv
    const windows = (await $.env.get('OS').catch(() => undefined)) === 'Windows_NT'
    const argv = windows ? ['powershell', '-NoProfile', '-Command', '(Get-UICulture).Name'] : ['defaults', 'read', '-g', 'AppleLanguages']
    const r = await $.process.run(argv, { timeoutMs: 5_000 }).catch(() => null)
    if (!r || r.exitCode !== 0) return 'en'
    // macOS prints a list such as ( "en-AU", "zh-Hans-AU" ); Windows prints one name such as zh-CN.
    const first = windows ? r.stdout.trim() : /\(\s*"?([^",\s)]+)/.exec(r.stdout)?.[1]
    return langOf(first) ?? 'en'
  } catch {
    return 'en'
  }
}

// Detected once per load (per setting), then reused. Only a settled answer is kept, so a lookup
//   that never settles (its engine gone) is never handed to a later caller.
let loaded: { setting: unknown; lang: Lang } | undefined
export async function langFor($: Pick<EngineInterface, 'env' | 'process'>, setting: unknown): Promise<Lang> {
  if (loaded && loaded.setting === setting) return loaded.lang
  const lang = await detectLang($, setting)
  loaded = { setting, lang }
  return lang
}

